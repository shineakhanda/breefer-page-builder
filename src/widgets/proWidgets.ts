import type { ControlDef, OptionsSource, SelectOption, WidgetDef } from '../types';

/**
 * Compact control builders so each widget definition stays readable.
 * Options are written as 'value=Label' pairs.
 */
function options(...pairs: string[]): SelectOption[] {
  return pairs.map((pair) => {
    const at = pair.indexOf('=');

    return at < 0
      ? { value: pair, label: pair }
      : { value: pair.slice(0, at), label: pair.slice(at + 1) };
  });
}

const text = (key: string, label: string, placeholder?: string): ControlDef => ({
  key,
  label,
  type: 'text',
  placeholder,
});

const area = (key: string, label: string, rows = 4, placeholder?: string): ControlDef => ({
  key,
  label,
  type: 'textarea',
  rows,
  placeholder,
});

const num = (
  key: string,
  label: string,
  min: number,
  max: number,
  unit?: string,
  group?: ControlDef['group'],
  step?: number,
): ControlDef => ({ key, label, type: 'number', min, max, unit, group, step });

const select = (
  key: string,
  label: string,
  choices: SelectOption[],
  group?: ControlDef['group'],
): ControlDef => ({ key, label, type: 'select', options: choices, group });

const dynamicSelect = (key: string, label: string, source: OptionsSource): ControlDef => ({
  key,
  label,
  type: 'select',
  optionsSource: source,
});

const color = (key: string, label: string): ControlDef => ({
  key,
  label,
  type: 'color',
  group: 'style',
});

const toggle = (key: string, label: string): ControlDef => ({ key, label, type: 'toggle' });

const align: ControlDef = {
  key: 'align',
  label: 'Alignment',
  type: 'select',
  group: 'style',
  options: options('left=Left', 'center=Center', 'right=Right'),
};

const margin: ControlDef = {
  key: 'margin',
  label: 'Margin',
  type: 'number',
  group: 'style',
  min: 0,
  max: 400,
  unit: 'px',
};

const headingTags = options('h1=H1', 'h2=H2', 'h3=H3', 'h4=H4', 'p=Paragraph', 'div=Div');

function inTwoWeeks(): string {
  const date = new Date(Date.now() + 14 * 24 * 60 * 60 * 1000);

  return `${date.toISOString().slice(0, 10)} 23:59`;
}

